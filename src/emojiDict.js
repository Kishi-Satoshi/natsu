// [{ e, n, y, c }]（e: 絵文字・n: 名前・y: よみ・c: 分類の key）。並びは分類の順・表の順
const EMOJI = Object.freeze(Object.entries(TABLE).flatMap(([c, text]) => text.trim().split('\n').map((line) => {
  const [e, n, y] = line.trim().split(/\s+/);
  return Object.freeze({ e, n, y, c });
})));
const BY_E = new Set(EMOJI.map((x) => x.e));

// 既定のアイコン（決めたこと 36。icon が無ければ議事録は 🎙️・白紙のページは 📄。0.16.0 DX-1（前提 P6）: データベースは 🗃️）
const DEFAULT_ICON = Object.freeze({ meeting: '🎙️', blank: '📄', database: '🗃️' });

// 辞書の絵文字（ちょうどその1つ）か。書記素が1つでないもの・文・辞書に無い絵文字は偽
function isPageIcon(v) {
  return typeof v === 'string' && v !== '' && BY_E.has(v);
}

// 探す語と名前を寄せる: 全角と半角（NFKC）・英字の大小・カタカナをひらがなに・空白を除く
function fold(s) {
  return String(s ?? '').normalize('NFKC').toLowerCase().replace(/[\u30a1-\u30f6]/g, (ch) => String.fromCharCode(ch.charCodeAt(0) - 0x60)).replace(/\s+/g, '');
}
const FOLDED = EMOJI.map((x) => ({ e: x.e, keys: [fold(x.n), x.y] }));

// 名前とよみで探す → [e]（前方一致が先・どちらも辞書の順。空の語は []）
function findEmoji(q) {
  const k = fold(q);
  if (!k) return [];
  const head = [];
  const part = [];
  for (const x of FOLDED) {
    if (x.keys.some((s) => s.startsWith(k))) head.push(x.e);
    else if (x.keys.some((s) => s.includes(k))) part.push(x.e);
  }
  return [...head, ...part];
}

// 一覧の1行（か、ページ）のアイコン: icon が辞書の絵文字ならそれ、無ければ（'' も辞書に無い値も）kind の既定（決めたこと 36・38）
function pageIconOf(entry) {
  if (entry && isPageIcon(entry.icon)) return entry.icon;
  if (entry && entry.kind === 'database') return DEFAULT_ICON.database;
  return entry && entry.kind === 'blank' ? DEFAULT_ICON.blank : DEFAULT_ICON.meeting;
}

